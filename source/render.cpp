void Game::drawText(const char* text, int x, int y, Uint8 r, Uint8 g, Uint8 b, int scale) {
    int cx = x;
    Uint32 c = getColor(r, g, b);
    for (int i = 0; text[i] != 0; i++) {
        unsigned char ch = (unsigned char)text[i];
        if (ch == ' ') { cx += 6 * scale; continue; }
        if (ch < 32 || ch > 126) { cx += 6 * scale; continue; }
        for (int row = 0; row < 7; row++) {
            Uint8 bits = FONT[ch][row];
            for (int col = 0; col < 5; col++) {
                if (bits & (0x10 >> col)) {
                    SDL_Rect rc = {(Sint16)(cx + col * scale), (Sint16)(y + row * scale), (Uint16)scale, (Uint16)scale};
                    SDL_FillRect(screen, &rc, c);
                }
            }
        }
        cx += 6 * scale;
    }
}

// Desenha um "cubo" 3D falso
void drawIsoCube(SDL_Surface* screen, Vec2 pos, float size, Uint8 r, Uint8 g, Uint8 b) {
    Uint32 topColor = SDL_MapRGB(screen->format, r, g, b);
    Uint32 leftColor = SDL_MapRGB(screen->format, (Uint8)(r*0.6f), (Uint8)(g*0.6f), (Uint8)(b*0.6f)); // Sombra
    Uint32 rightColor = SDL_MapRGB(screen->format, (Uint8)(r*0.4f), (Uint8)(g*0.4f), (Uint8)(b*0.4f)); // Sombra escura

    // Topo do cubo
    SDL_Rect top = {(Sint16)(pos.x - size), (Sint16)(pos.y - size*0.5f), (Uint16)(size*2), (Uint16)(size)};
    SDL_FillRect(screen, &top, topColor);

    // Lado esquerdo
    SDL_Rect left = {(Sint16)(pos.x - size), (Sint16)(pos.y + size*0.5f), (Uint16)size, (Uint16)(size)};
    SDL_FillRect(screen, &left, leftColor);

    // Lado direito
    SDL_Rect right = {(Sint16)(pos.x), (Sint16)(pos.y + size*0.5f), (Uint16)size, (Uint16)(size)};
    SDL_FillRect(screen, &right, rightColor);
    
    // Borda preta para dar definição (opcional)
    SDL_Rect bordaTop = {(Sint16)(pos.x - size), (Sint16)(pos.y - size*0.5f), (Uint16)(size*2), 1};
    SDL_FillRect(screen, &bordaTop, SDL_MapRGB(screen->format, 0, 0, 0));
}

void Game::render() {
    // 1. Fundo (Céu azul claro)
    SDL_Rect bg = {0, 0, (Uint16)screen->w, (Uint16)screen->h};
    SDL_FillRect(screen, &bg, getColor(100, 180, 255));

    // 2. Chão de Grama Verde
    Vec2 chaoCentro = worldToScreen(GRID_SIZE * CELL_SIZE / 2.0f, GRID_SIZE * CELL_SIZE / 2.0f);
    SDL_Rect chao = {
        (Sint16)(chaoCentro.x - (GRID_SIZE * CELL_SIZE * 0.8f)), 
        (Sint16)(chaoCentro.y - (GRID_SIZE * CELL_SIZE * 0.4f)), 
        (Uint16)(GRID_SIZE * CELL_SIZE * 1.6f), 
        (Uint16)(GRID_SIZE * CELL_SIZE * 0.8f)
    };
    SDL_FillRect(screen, &chao, getColor(50, 180, 50));

    // 3. A Cerca (Fake 3D) - Desenha as bordas do grid
    for (int i = 0; i <= GRID_SIZE; i++) {
        // Cerca de cima e de baixo
        Vec2 p1 = worldToScreen(i * CELL_SIZE, 0);
        Vec2 p2 = worldToScreen(i * CELL_SIZE, GRID_SIZE * CELL_SIZE);
        drawIsoCube(screen, p1, 3, 139, 69, 19); // Postes marrons
        drawIsoCube(screen, p2, 3, 139, 69, 19);
        
        // Cerca lateral esquerda e direita
        Vec2 p3 = worldToScreen(0, i * CELL_SIZE);
        Vec2 p4 = worldToScreen(GRID_SIZE * CELL_SIZE, i * CELL_SIZE);
        drawIsoCube(screen, p3, 3, 139, 69, 19);
        drawIsoCube(screen, p4, 3, 139, 69, 19);
    }

    // 4. A Maçã (Vermelha)
    Vec2 applePos = worldToScreen(apple.x * CELL_SIZE + CELL_SIZE/2, apple.y * CELL_SIZE + CELL_SIZE/2);
    drawIsoCube(screen, applePos, 8, 220, 20, 20);

    // 5. O Corpo da Cobra (Blocos Verdes)
    for (int i = (int)player.body.size() - 1; i >= 0; i--) {
        Vec2 pos = worldToScreen(player.body[i].x * CELL_SIZE + CELL_SIZE/2, player.body[i].y * CELL_SIZE + CELL_SIZE/2);
        // Cabeça um pouco mais clara
        if (i == 0) drawIsoCube(screen, pos, 10, 100, 255, 100); 
        else drawIsoCube(screen, pos, 10, 50, 200, 50);
    }

    // 6. Placar (Estilo Minecraft)
    int mx = screen->w - 250;
    int my = 20;
    SDL_Rect placarBg = {(Sint16)mx, (Sint16)my, 230, 80};
    SDL_FillRect(screen, &placarBg, getColor(50, 50, 50)); // Fundo cinza escuro
    SDL_Rect placarBg2 = {(Sint16)(mx+2), (Sint16)(my+2), 226, 76};
    SDL_FillRect(screen, &placarBg2, getColor(100, 100, 100)); // Fundo cinza claro

    char buf[64];
    snprintf(buf, sizeof(buf), "Atual: %d", score);
    drawText(buf, mx + 10, my + 10, 255, 255, 255, 2);
    
    snprintf(buf, sizeof(buf), "Recorde: %d", record);
    drawText(buf, mx + 10, my + 40, 255, 50, 50, 2); // Vermelho

    // 7. Game Over
    if (gameState == 2) {
        SDL_Rect box = {(Sint16)(screen->w/2 - 200), (Sint16)(screen->h/2 - 60), 400, 120};
        SDL_FillRect(screen, &box, getColor(0, 0, 0));
        drawText("GAME OVER", screen->w/2 - 80, screen->h/2 - 30, 255, 50, 50, 4);
        drawText("APERTE X PARA VOLTAR", screen->w/2 - 120, screen->h/2 + 20, 255, 255, 255, 2);
    }

    SDL_Flip(screen);
}