void Game::drawFilledCircle(int cx, int cy, int radius, Uint8 r, Uint8 g, Uint8 b) {
    if (radius <= 0) return;
    Uint32 c = getColor(r, g, b);
    for (int y = -radius; y <= radius; y++) {
        int w = (int)sqrtf((float)(radius * radius - y * y));
        SDL_Rect rc = {(Sint16)(cx - w), (Sint16)(cy + y), (Uint16)(w * 2), 1};
        SDL_FillRect(screen, &rc, c);
    }
}

void Game::drawRect(int x, int y, int w, int h, Uint8 r, Uint8 g, Uint8 b) {
    SDL_Rect rc = {(Sint16)x, (Sint16)y, (Uint16)w, (Uint16)h};
    SDL_FillRect(screen, &rc, getColor(r, g, b));
}

void Game::drawText(const char* text, int x, int y, Uint8 r, Uint8 g, Uint8 b, int scale) {
    int cx = x;
    Uint32 c = getColor(r, g, b);
    for (int i = 0; text[i] != 0; i++) {
        unsigned char ch = (unsigned char)text[i];
        if (ch == ' ') { cx += 6 * scale; continue; }
        if (ch < 32 || ch > 126) { cx += 6 * scale; continue; }
        for (int row = 0; row < 7; row++) {
            Uint8 bits = FONT[ch][row];
            for (int col = 0; col < 5; col++) {
                if (bits & (0x10 >> col)) {
                    SDL_Rect rc = {(Sint16)(cx + col * scale), (Sint16)(y + row * scale), (Uint16)scale, (Uint16)scale};
                    SDL_FillRect(screen, &rc, c);
                }
            }
        }
        cx += 6 * scale;
    }
}

// Fundo Azul Roya e Grade Quadriculada (igual a foto)
void Game::drawGrid() {
    // Azul Royal da foto
    drawRect(0, 0, screen->w, screen->h, 30, 60, 200); 
    
    int gridSize = 60 * zoom;
    int offX = (int)(-cameraX * zoom) % gridSize;
    int offY = (int)(-cameraY * zoom) % gridSize;
    if (offX > 0) offX -= gridSize;
    if (offY > 0) offY -= gridSize;

    for (int x = offX; x < screen->w; x += gridSize) {
        drawRect(x, 0, 2, screen->h, 50, 90, 220); // Linha vertical azul claro
    }
    for (int y = offY; y < screen->h; y += gridSize) {
        drawRect(0, y, screen->w, 2, 50, 90, 220); // Linha horizontal
    }
}

void Game::drawBorder() {
    Vec2 center = worldToScreen(0, 0);
    int rad = (int)(WORLD_RADIUS * zoom);
    // Desenha uma borda vermelha fina no mundo todo
    for (int a = 0; a < 360; a += 2) {
        float ar = a * 3.14159f / 180.0f;
        int px = center.x + (int)(cosf(ar) * rad);
        int py = center.y + (int)(sinf(ar) * rad);
        drawRect(px, py, 3, 3, 255, 50, 50);
    }
}

void Game::drawFood() {
    for (int i = 0; i < MAX_FOOD; i++) {
        if (!foods[i].active) continue;
        Vec2 s = worldToScreen(foods[i].pos.x, foods[i].pos.y);
        drawFilledCircle((int)s.x, (int)s.y, (int)(foods[i].radius * zoom), foods[i].r, foods[i].g, foods[i].b);
    }
}

// Desenha a cobra em bolinhas (igual foto)
void Game::drawSnake(Snake& s) {
    if (!s.alive) return;
    int rad = (int)(s.radius * zoom);
    if (rad < 2) rad = 2;

    for (int i = (int)s.body.size() - 1; i >= 0; i--) {
        Vec2 sc = worldToScreen(s.body[i].x, s.body[i].y);
        
        // Sombra/contorno escuro
        drawFilledCircle((int)sc.x, (int)sc.y, rad + 1, 10, 20, 80);
        
        // Cor da bolinha
        drawFilledCircle((int)sc.x, (int)sc.y, rad, s.r, s.g, s.b);
        
        // Brilho interno (dá o efeito 3D/Neon)
        drawFilledCircle((int)sc.x - rad/3, (int)sc.y - rad/3, rad/3, 255, 255, 255);
    }
}

void Game::drawMinimap() {
    int mSize = 150;
    int mx = screen->w - mSize - 20;
    int my = 20;
    
    // Fundo do minimapa
    drawRect(mx, my, mSize, mSize, 20, 40, 150);
    
    for (int i = 0; i < MAX_SNAKES; i++) {
        if (!snakes[i].alive || snakes[i].body.empty()) continue;
        Vec2 head = snakes[i].body.front();
        
        // Converte pro espaço do minimapa
        int px = mx + mSize/2 + (int)(head.x / WORLD_RADIUS * (mSize/2));
        int py = my + mSize/2 + (int)(head.y / WORLD_RADIUS * (mSize/2));
        
        drawRect(px-2, py-2, 4, 4, snakes[i].r, snakes[i].g, snakes[i].b);
    }
}

void Game::drawHUD() {
    char buf[64];
    snprintf(buf, sizeof(buf), "PONTOS: %d", snakes[0].score);
    drawText(buf, 20, 20, 255, 255, 255, 3);
    
    if (!snakes[0].alive) {
        drawRect(screen->w/2 - 200, screen->h/2 - 50, 400, 100, 0, 0, 0);
        drawText("VOCE MORREU!", screen->w/2 - 170, screen->h/2 - 30, 255, 50, 50, 4);
        drawText("APERTE X PARA VOLTAR", screen->w/2 - 130, screen->h/2 + 10, 255, 255, 255, 2);
    }
}

void Game::render() {
    drawGrid();
    drawBorder();
    drawFood();
    
    for (int i = 0; i < MAX_SNAKES; i++) {
        drawSnake(snakes[i]);
    }
    
    drawMinimap();
    drawHUD();
    
    SDL_Flip(screen);
}